const CHAPTER_INDEX = new Map<string, VeilChapter>();
for (const chapter of VEIL_CHAPTERS) {
  CHAPTER_INDEX.set(chapter.id, chapter);
  CHAPTER_INDEX.set(String(chapter.chapter), chapter);
}

/**
 * 章番号（1..10）または章id（'veil-ch01'）から章メタを取得する。
 * 未知の値は例外にする（章の取り違えを黙って通さない）。
 */
export function veilChapter(chapterOrId: number | string): VeilChapter {
  const key = typeof chapterOrId === 'number' ? String(chapterOrId) : chapterOrId;
  const found = CHAPTER_INDEX.get(key);
  if (!found) throw new Error(`unknown veil chapter: ${String(chapterOrId)}`);
  return found;
}

/** 章末の選択肢を id で引く。未知の選択肢は例外にする。 */
export function veilChoiceOption(chapterOrId: number | string, optionId: string): VeilChoiceOption {
  const chapter = veilChapter(chapterOrId);
  const option = chapter.choice.options.find((entry) => entry.id === optionId);
  if (!option) throw new Error(`unknown veil choice option: ${chapter.id}/${optionId}`);
  return option;
}
