/**
 * THE VEIL FRONT / 十章キャンペーンの章メタデータ。
 *
 * ここは「章の内容」だけを持つ。ミッション定義（敵配置・目標判定）は
 * `src/content/veil/missions.ts` 側で `missionId` を鍵に定義する。
 *
 * 設計上の約束（ストーリー_十章作戦記録.html §03 準拠）:
 * - 選択に「正解」を作らない。どちらを選んでも何かを得て、何かを失う。
 * - 分岐で章を増やさない。選択は次章の僚機・補給・通信・援護を変えるだけ。
 * - 効果は4状態（帰還者／航路信頼／軍令信用／敵エースの誓約）への増減で表す。
 *   各値は -15..+15、1章あたりの増減の総量は ±15 程度に収める。
 *
 * 注意: `theater` は `world.ts` の戦域idと対応させるが、循環参照と
 * 作成順の依存を避けるため文字列で保持する（import しない）。
 */

/** 4状態への増減。値域は -15..+15。 */
export interface VeilChoiceEffects {
  /** 帰還者: 上=救難・僚機援護・発砲回避 / 下=追撃・戦果優先 */
  returnees?: number;
  /** 航路信頼: 上=中立規約の順守・証拠公開 / 下=民間損害・協定違反 */
  routeTrust?: number;
  /** 軍令信用: 上=命令順守・損害の最小化 / 下=無許可出撃・内部告発 */
  commandTrust?: number;
  /** 敵エースの誓約: 上=決闘規約の尊重・救難優先 / 下=撃墜後の侮辱・降伏者の放置 */
  aceOath?: number;
}

export interface VeilChoiceOption {
  /** 安定キー。保存データに残るので変更しない。 */
  id: string;
  /** 選択肢の表示文 */
  label: string;
  /** 次章に何が変わるかを1行で（「正解／不正解」ではなく帰結） */
  consequence: string;
  /** 4状態への増減 */
  effects: VeilChoiceEffects;
}

export interface VeilChoice {
  /** 見出し（例 'FIELD CHOICE' 'COMMAND TENSION' 'HONOR CLAUSE'） */
  kind: string;
  /** 問いの文 */
  question: string;
  /** 補足（選択の帰結を示す一文） */
  note: string;
  options: VeilChoiceOption[];
}

export interface VeilChapter {
  /** 1..10 */
  chapter: number;
  /** キャンペーンノードid。'veil-ch01' 形式 */
  id: string;
  /** ミッションid。ノードidと同一 */
  missionId: string;
  /** 例 'OPERATION CINDER BEACON' */
  operation: string;
  /** 戦域id（world.ts の VEIL_THEATERS と対応） */
  theater: string;
  /** 戦域の表示名 */
  theaterName: string;
  /** 章タイトル */
  title: string;
  /** 章の見出し語（章一覧に並ぶ短い語） */
  shortTitle: string;
  /** 引用のタグライン */
  tagline: string;
  /** 章カードの本文6段落 */
  body: string[];
  /** 主目標の表示文 */
  objective: string;
  /** 機体フック／戦場特性／実戦テーマなどの副見出しと値 */
  hook: { label: string; value: string };
  /** 登場人物（人物idと表示名） */
  cast: Array<{ id?: string; name: string }>;
  /** 章末の選択 */
  choice: VeilChoice;
  /** ブリーフィング背景に使う章画像の相対パス */
  image: string;
}

