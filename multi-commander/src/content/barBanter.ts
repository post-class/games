/**
 * 掛け合いの前に置く1行。`idle` のときは `undefined`（前振り無し）。
 *
 * `mourning` のときだけ戦死者名を差し込む（名前が無ければ「あの人」）。
 */
export function banterIntro(
  kind: PilotBondKind,
  topic: BanterTopic,
  seed: number,
  fallenName?: string,
): BanterLine | undefined {
  if (topic === 'idle') return undefined;
  const set = INTROS[kind][topic];
  if (!set || set.length === 0) return undefined;
  const line = pickAt(set, seed);
  return { speaker: line.speaker, text: line.text.replace('{name}', fallenName || 'あの人') };
}

