/**
 * 酒場の掛け合い（T8-②）の台詞素材。
 *
 * ■ 何のための素材か
 * これまでの酒場（`src/content/pilotDialogue.ts` の「酒場の往復会話」節）は
 * **プレイヤーと隊員1人**の会話だった。ここに置くのは、
 * **隊員2人が互いに話しているところへプレイヤーが割り込む**ための台詞である。
 * 誰と誰が何を言い合うかは `src/content/pilotBonds.ts` の10ペアが決める。
 *
 * ■ rng を使わない
 * `pilotDialogue.ts` と同じ規約。同じ画面を開き直すたびに文が変わると、
 * 割り込みで何が変わったのか読めなくなる（テストも固定できない）。
 * 台詞の揺らぎは呼び出し側が渡す `seed` で決め、`pickAt` と同じ式で選ぶ。
 *
 * ■ 構成
 *   [話題の前振り 1行]              ← 相関の種類 × 話題（`idle` のときは無し）
 *   掛け合い 3行（a → b → a）        ← ペア固有。2バリアントを seed で選ぶ
 *   [プレイヤーの割り込み 3択]        ← ペア固有。バリアントごとに噛み合う言葉
 *   反応 2行（a と b が1行ずつ）      ← 相関の種類 × 選んだ択
 *
 * 前振りと反応は「関係の種類」単位なので名前を含めない（どのペアでも成立する）。
 * ペアにしか言えない内容は、すべて掛け合い3行と3択のラベルに入れてある。
 */

import { bondKey, type PilotBondKind } from './pilotBonds';

/**
 * 掛け合いの話題。直前の出撃で「この二人に何が起きたか」で決まる。
 * 判定は `src/app/barBanter.ts` の `banterTopic` が行う。
 */
export type BanterTopic =
  /** 直前の出撃について（二人のどちらかが僚機として飛んだ） */
  | 'aftermath'
  /** 直近の戦死者について */
  | 'mourning'
  /** プレイヤーが救援要請に応えた直後 */
  | 'rescue'
  /** プレイヤーが救援要請を無視した直後 */
  | 'neglect'
  /** それ以外 */
  | 'idle';

/** プレイヤーの割り込み方。3択で、効果の向きが違う。 */
export type BanterChoice = 'side-a' | 'side-b' | 'defuse';

export const BANTER_CHOICES: readonly BanterChoice[] = ['side-a', 'side-b', 'defuse'];

/** 掛け合い1バリアント（3行の並びは a → b → a 固定）。 */
export interface BanterVariant {
  /** a の1行目、b の返し、a の締め。 */
  lines: readonly [string, string, string];
  /** その掛け合いに噛み合うプレイヤーの3択。 */
  replies: Readonly<Record<BanterChoice, string>>;
}

interface PairBanter {
  a: string;
  b: string;
  /** seed で選ぶ2バリアント。 */
  variants: readonly [BanterVariant, BanterVariant];
}

/**
 * `pilotDialogue.ts` の `pickAt` と同じ決定論的な選び方。
 * 負の seed でも同じ添字に落ちるように剰余を正規化する。
 */
function indexAt(seed: number, length: number): number {
  if (length <= 0) return 0;
  const n = Number.isFinite(seed) ? Math.trunc(seed) : 0;
  return ((n % length) + length) % length;
}

function pickAt<T>(list: readonly T[], seed: number): T {
  return list[indexAt(seed, list.length)];
}

