const PAIR_BY_KEY = new Map<string, PairBanter>(PAIR_BANTER.map((p) => [bondKey(p.a, p.b), p]));

/** 掛け合いの1行。`speaker` は `PilotBond` の `a` / `b`。 */
export interface BanterLine {
  speaker: 'a' | 'b';
  text: string;
}

/**
 * ペア固有の掛け合い3行（a → b → a）。
 *
 * `seed` で2バリアントのどちらかを選ぶ。相関を持たない組み合わせを渡したら
 * 空配列（呼び出し側は `bondBetween` で得たペアしか渡さない想定）。
 */
export function banterExchange(a: string, b: string, seed: number): BanterLine[] {
  const pair = PAIR_BY_KEY.get(bondKey(a, b));
  if (!pair) return [];
  const variant = pickAt(pair.variants, seed);
  return [
    { speaker: 'a', text: variant.lines[0] },
    { speaker: 'b', text: variant.lines[1] },
    { speaker: 'a', text: variant.lines[2] },
  ];
}

/**
 * ペア固有の3択ラベル。
 *
 * 掛け合いのバリアントと同じ `seed` で引くので、**表示中の掛け合いに噛み合う**
 * 言葉が出る（汎用の「味方する／なだめる」にはしない）。
 */
export function banterReplyLabel(a: string, b: string, choice: BanterChoice, seed: number): string {
  const pair = PAIR_BY_KEY.get(bondKey(a, b));
  if (!pair) return '';
  return pickAt(pair.variants, seed).replies[choice];
}

